#  โปรแกรมคำนวณพื้นที่รูปทรงต่างๆ
#  พัฒนาโดย: สุริยะกาญจน์ จารัตน์
# ===================================

def เส้นคั่น():
    print("=" * 40)

def คำนวณสี่เหลี่ยมมุมฉาก():
    print("📐 คำนวณพื้นที่สี่เหลี่ยมมุมฉาก")
    กว้าง = float(input("   กรอกความกว้าง: "))
    ยาว = float(input("   กรอกความยาว: "))
    พื้นที่ = กว้าง * ยาว
    เส้นคั่น()
    print(f"   ✅ พื้นที่ = {กว้าง} × {ยาว} = {พื้นที่} ตารางหน่วย")

def คำนวณวงกลม():
    print("⭕ คำนวณพื้นที่วงกลม")
    รัศมี = float(input("   กรอกรัศมี: "))
    พื้นที่ = 3.14159 * รัศมี ** 2
    เส้นคั่น()
    print(f"   ✅ พื้นที่ = 3.14159 × {รัศมี}² = {พื้นที่:.2f} ตารางหน่วย")

def คำนวณสามเหลี่ยม():
    print("🔺 คำนวณพื้นที่สามเหลี่ยม")
    ฐาน = float(input("   กรอกความยาวฐาน: "))
    สูง = float(input("   กรอกความสูง: "))
    พื้นที่ = 0.5 * ฐาน * สูง
    เส้นคั่น()
    print(f"   ✅ พื้นที่ = ½ × {ฐาน} × {สูง} = {พื้นที่} ตารางหน่วย")

# ===== โปรแกรมหลัก =====
while True:
    เส้นคั่น()
    print("   🧮 โปรแกรมคำนวณพื้นที่รูปทรง")
    เส้นคั่น()
    print("   1️⃣  สี่เหลี่ยมมุมฉาก")
    print("   2️⃣  วงกลม")
    print("   3️⃣  สามเหลี่ยม")
    print("   0️⃣  ออกจากโปรแกรม")
    เส้นคั่น()

    เลือก = input("   เลือกรูปทรง (0-3): ")

    เส้นคั่น()

    if เลือก == "1":
        คำนวณสี่เหลี่ยมมุมฉาก()
    elif เลือก == "2":
        คำนวณวงกลม()
    elif เลือก == "3":
        คำนวณสามเหลี่ยม()
    elif เลือก == "0":
        เส้นคั่น()
        print("   👋 ขอบคุณที่ใช้โปรแกรม!")
        เส้นคั่น()
        break
    else:
        print("   ❌ กรุณาเลือก 0-3 เท่านั้น")

    input("\n   กด Enter เพื่อคำนวณใหม่...")